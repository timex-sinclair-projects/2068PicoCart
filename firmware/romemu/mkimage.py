#!/usr/bin/env python3
"""Build the 64 KB dock image header (rom_image.h) for the romemu firmware.

  mkimage.py out.h IMAGE.dck
  mkimage.py out.h IMAGE.bin[@ADDR] [MORE.bin@ADDR ...]     (ADDR hex or decimal; default 0x8000)

A .dck file: 9-byte header [bank][chunk0..chunk7], then 8 KB of data for each chunk whose
type has bit 1 set, in chunk order. Type bit 0 = RAM: 0 absent, 1 empty RAM, 2 ROM, 3 RAM
with initial contents. Only bank 0 (DOCK) is used.
A .bin file is a raw ROS image (AROS: header at $8000). Unused bytes are 0xFF, what an
empty dock reads. Also writes a chunk mask: bit n = chunk n holds cartridge data.
"""
import sys


def main():
    out, srcs = sys.argv[1], sys.argv[2:]
    img = bytearray(b"\xff" * 65536)
    mask = 0
    ram = 0
    names = []
    for src in srcs:
        path, _, at = src.partition("@")
        data = open(path, "rb").read()
        names.append(src)
        if path.lower().endswith(".dck"):
            bank, types, body = data[0], data[1:9], data[9:]
            if bank != 0:
                sys.exit(f"{path}: bank {bank} is not the DOCK bank")
            pos = 0
            for n, t in enumerate(types):
                if t & 1:
                    ram |= 1 << n
                if not t & 2:
                    continue
                img[n * 8192:(n + 1) * 8192] = body[pos:pos + 8192]
                pos += 8192
                mask |= 1 << n
        else:
            addr = int(at, 0) if at else 0x8000
            if addr + len(data) > 65536:
                sys.exit(f"{path}: {len(data)} bytes at {addr:#06x} runs past 64 KB")
            img[addr:addr + len(data)] = data
            for n in range(addr // 8192, (addr + len(data) + 8191) // 8192):
                mask |= 1 << n
    with open(out, "w") as f:
        f.write(f"// generated by mkimage.py from {' '.join(names)}\n")
        f.write(f"#define ROM_IMAGE_CHUNKS 0x{mask:02x}\n#define ROM_IMAGE_RAM 0x{ram:02x}\n")
        f.write(f'#define ROM_IMAGE_NAME "{" ".join(n.split("/")[-1] for n in names)}"\n')
        f.write("static const uint8_t rom_image_flash[65536] = {\n")
        for i in range(0, 65536, 16):
            f.write("  " + ",".join(f"0x{b:02x}" for b in img[i:i + 16]) + ",\n")
        f.write("};\n")
    print(f"wrote {out}: chunks {mask:08b} (bit n = chunk n), RAM {ram:08b}")


if __name__ == "__main__":
    main()
